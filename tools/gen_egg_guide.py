# -*- coding: utf-8 -*-
"""从 index.html 的 EGGS / EGG_ALT 注册表自动生成《彩蛋完整解锁方法.md》

用法：项目根目录跑 `python tools/gen_egg_guide.py`（在别的目录跑也行，路径按脚本位置算）。
加减彩蛋后重新跑一次，文档永远和注册表同步。
"""
import io, re, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
s = io.open(os.path.join(ROOT, 'index.html'), encoding='utf-8').read()

m = re.search(r"const EGGS = \[(.*?)\n\];", s, re.S)
assert m, '没找到 EGGS 注册表'
rows = []
for line in m.group(1).split('\n'):
    line = line.strip()
    if not line.startswith('{ id:'):
        continue
    g = re.match(r"\{ id:'([^']+)', cat:'([^']+)', fx:'([^']+)', name:'([^']+)', trig:'([^']+)', secret:'([^']+)'", line)
    assert g, '解析不了这一行：' + line[:100]
    rows.append({
        'id': g.group(1), 'cat': g.group(2), 'fx': g.group(3),
        'name': g.group(4), 'trig': g.group(5), 'secret': g.group(6)
    })
assert len(rows) == 52, '彩蛋数量不对：%d' % len(rows)

ma = re.search(r"const EGG_ALT = \{(.*?)\n\};", s, re.S)
assert ma, '没找到 EGG_ALT'
alt = {}
for k, v in re.findall(r"'([^']+)':'([^']+)'", ma.group(1)):
    alt[k] = v
assert len(alt) >= 16, '替代暗号偏少：%d' % len(alt)


def cell(x):
    return str(x).replace('|', '\\|').replace('\n', ' ')


cats = ['暗号', '字符', '键盘', '手势', '时间', '游戏', '开发者']
out = []
w = out.append

w('# 彩蛋完整解锁方法（全剧透版）')
w('')
w('> 适用版本：**v0.2.25** ｜ 一共 **52 个** ｜ 网页版 / 安卓 APK / Windows EXE 都能照着做')
w('> 图鉴怎么开：设置 → 最顶上那个「字」图标**长按 1.2 秒**')
w('> 应用内也有这份攻略：图鉴 → 「📖 完整解锁方法（全剧透）」，每条还带「直接玩一次」按钮')
w('')
w('> ⚠️ 这是**全剧透**。想自己找就别往下翻 —— 图鉴里没发现的只给谜面，找到后才摊开答案。')
w('')
w('---')
w('')
w('## 一、先讲「替代暗号」是什么（这次新加的）')
w('')
w('以前有几个彩蛋在特定设备上**永远解不开**，图鉴就差那么几个凑不齐：')
w('')
w('| 卡在哪 | 原本要干嘛 | 哪些端做不了 |')
w('|---|---|---|')
w('| 没地址栏 / 没控制台 | F12 敲 `eggHelp()`、网址加 `?mode=80s`、加 `#unicode` | 安卓 APK、Windows EXE（都是 WebView，没地址栏也没 devtools） |')
w('| 没陀螺仪 | 摇一摇手机、转成横屏 | 网页版（电脑）、Windows EXE |')
w('| 没物理键盘 | 方向键秘技、不在输入框敲字、连按 Esc、按 `?` | 手机 |')
w('| 得等日子 | 愚人节、2 月 29 日、周五、凌晨、节日、断网 | 看日历，不是设备问题，但等不起 |')
w('')
w('**现在的统一解法：在「搜索」页的输入框里输入那一串「替代暗号」，按回车。**')
w('彩蛋照常播放、图鉴照样 +1，而且**不会拦住正常搜索**（暗号也可以当普通词查）。')
w('原来的触发方式一个都没删，浏览器里照样能 F12、照样能改网址。')
w('')
w('共 %d 个彩蛋有替代暗号，全文里标在「全端替代」这一列。' % len(alt))
w('')
w('## 二、52 个逐条')
w('')
w('表格怎么看：')
w('')
w('- **怎么触发** = 原本的解法（有设备限制）')
w('- **全端替代** = 搜索框里输入这个暗号，任何设备都行；写「—」表示本来三端都能做')
w('- **效果** = 这个彩蛋是哪种花样，不是都下字符雨（52 个里只有 1 个是满屏字符雨）')
w('- **线索** = 图鉴里没发现时给的谜面')
w('')

idx = 0
for cat in cats:
    sub = [r for r in rows if r['cat'] == cat]
    w('### %s（%d 个）' % (cat, len(sub)))
    w('')
    w('| # | 名称 | 怎么触发 | 全端替代 | 效果 | 线索 |')
    w('|---|---|---|---|---|---|')
    for r in sub:
        idx += 1
        a = alt.get(r['id'])
        w('| %02d | **%s** | %s | %s | %s | %s |' % (
            idx, cell(r['name']), cell(r['trig']),
            '`' + cell(a) + '`' if a else '—',
            cell(r['fx']), cell(r['secret'])))
    w('')
assert idx == 52, '分类汇总数量不对：%d' % idx

w('## 三、最快集齐路线（懒人版）')
w('')
w('1. 设置 → 长按最顶上的「字」图标 1.2 秒，打开**彩蛋图鉴**。')
w('2. 点顶部「📖 完整解锁方法（全剧透）」，里面 52 条每条都有「▶ 直接玩一次」，挨个点一遍就全解了 —— 不用改时间、不用换设备、不用 F12。')
w('3. 想按原味玩，就把下面这些暗号在搜索框里各输一次：')
w('')
w('   `' + '` `'.join(alt[k] for k in alt) + '`')
w('')
w('4. 剩下那些三端本来就能做的（搜文字暗号、查特定码位、点图标、玩小游戏），按上表「怎么触发」那列做一遍即可。')
w('')
w('## 四、几个容易卡住的点')
w('')
w('- **「设置滑到底 3 次」**：v0.2.24 把设置改成分组入口 + 小卡片后，主页变短、真正滚动的是卡片内容区，这个彩蛋一度三个端都触发不了。v0.2.25 修好了（主页和任意卡片里滚到底都算），也可以直接输暗号 `到底了`。')
w('- **「彩蛋图鉴」「码位挑战」「找不同」「字符名片」「码位电报」**：图鉴底部本来就有「小游戏 / 小工具（不用找，直接点）」一排按钮，不会因为只给谜面而形成死锁。')
w('- **「开发者」那 4 个**：`eggHelp()` 依旧能在浏览器控制台用；`?mode=80s`、`#unicode` 依旧能加在网页地址后面。APK / EXE 里请用替代暗号。')
w('- **时间类**：`夜猫子` / `愚人节` / `过节` / `周五` / `闰日` / `离线` / `横屏` 都有暗号，不用真的改系统时间或等四年。')
w('- **「随机试一个」**：从 v0.2.25 起不再跳过开发者类，没解完的都能被抽到。')
w('')
w('## 五、进度怎么算、会不会丢')
w('')
w('- 发现记录存在本机的 `unicode_egg_found_v2` 里，图鉴顶部有进度条。')
w('- **算个人数据**：导出 / 导入 JSON、取件码或文件同步、清空全部个人数据，都会带着它一起走；同步时接收方还能逐项勾选要不要收「彩蛋进度」。')
w('- 换设备记得先导出或同步，不然进度只留在这台机器上。')
w('- 想重玩：图鉴底部「清空发现记录」，清完可以重新找一遍。')
w('')
w('## 六、出处')
w('')
w('- 「点图标翻面」这个点子是学**字统网 zi.tools** 的（它点 logo 会变另一版风格），我们没照抄：做成宣纸底「字」⇄ 墨底金印两面来回翻。设置页图标下面也写了这句。')
w('- 「同形字」那套（O / Ο / О）就是 Unicode 的 confusables（UTS #39），图鉴里的「找不同」小游戏和新的「替换字」页都在讲它。')
w('')
w('---')
w('')
w('_这份文档由 `tools/gen_egg_guide.py` 从 `index.html` 的 `EGGS` / `EGG_ALT` 注册表自动生成；以后加减彩蛋，在项目根目录跑 `python tools/gen_egg_guide.py` 重新生成即可，不会出现文档和实际对不上的情况。_')

io.open(os.path.join(ROOT, '彩蛋完整解锁方法.md'), 'w', encoding='utf-8', newline='').write('\n'.join(out) + '\n')
print('生成完成：52 个彩蛋 / %d 个替代暗号 / %d 行' % (len(alt), len(out)))
